const normalizeRole = (role) => {
  if (role === ROLES.SUPERADMIN) return ROLES.SUPER_ADMIN;
  return role;
};

const getPermissionsForRole = (role) => {
  const normalized = normalizeRole(role);
  return ROLE_PERMISSIONS[normalized] || ROLE_PERMISSIONS[role] || [];
};

const resolvePermission = (permission) => PERMISSION_ALIASES[permission] || permission;

const hasPermission = (role, permission) => {
  const perms = getPermissionsForRole(role);
  const resolved = resolvePermission(permission);
  if (perms.includes(permission) || perms.includes(resolved)) return true;

  // Backward-compatible grants: category:* implies subcategory:* for older sessions
  const subcategoryFallback = {
    [PERMISSIONS.SUBCATEGORY_READ]: PERMISSIONS.CATEGORY_READ,
    [PERMISSIONS.SUBCATEGORY_CREATE]: PERMISSIONS.CATEGORY_CREATE,
    [PERMISSIONS.SUBCATEGORY_UPDATE]: PERMISSIONS.CATEGORY_UPDATE,
    [PERMISSIONS.SUBCATEGORY_DELETE]: PERMISSIONS.CATEGORY_DELETE,
    [PERMISSIONS.CATALOG_SUBCATEGORY_READ]: PERMISSIONS.CATEGORY_READ,
    [PERMISSIONS.CATALOG_SUBCATEGORY_CREATE]: PERMISSIONS.CATEGORY_CREATE,
    [PERMISSIONS.CATALOG_SUBCATEGORY_UPDATE]: PERMISSIONS.CATEGORY_UPDATE,
    [PERMISSIONS.CATALOG_SUBCATEGORY_DELETE]: PERMISSIONS.CATEGORY_DELETE,
  };
  const fallback = subcategoryFallback[permission] || subcategoryFallback[resolved];
  return fallback ? perms.includes(fallback) : false;
};

